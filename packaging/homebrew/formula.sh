#!/bin/sh
# Generate the Homebrew formula for gbomacfly/homebrew-tap from the .sha256
# files of a release. Used by the release CI; can be run by hand as well:
#
#   packaging/homebrew/formula.sh 0.3.3 dir-with-sha256-files > Formula/rbtop.rb
#
# The formula installs the prebuilt release binaries (no Rust toolchain needed):
# aarch64/x86_64 for macOS, static musl builds for Linux (Linuxbrew).
set -eu

version=${1:?usage: formula.sh <version> <dir with rbtop-v<version>-<target>.tar.gz.sha256>}
dir=${2:?usage: formula.sh <version> <dir>}
base="https://github.com/gbomacfly/rbtop/releases/download/v$version"

sha() {
    f="$dir/rbtop-v$version-$1.tar.gz.sha256"
    [ -s "$f" ] || { echo "missing $f" >&2; exit 1; }
    s=$(cut -d' ' -f1 "$f")
    case $s in
        *[!0-9a-f]*|"") echo "bad checksum in $f" >&2; exit 1 ;;
    esac
    [ ${#s} -eq 64 ] || { echo "bad checksum length in $f" >&2; exit 1; }
    printf '%s' "$s"
}

mac_arm=$(sha aarch64-apple-darwin)
mac_x86=$(sha x86_64-apple-darwin)
lin_arm=$(sha aarch64-unknown-linux-musl)
lin_x86=$(sha x86_64-unknown-linux-musl)

cat <<EOF
# Generated by packaging/homebrew/formula.sh in gbomacfly/rbtop - do not edit by hand,
# the release CI overwrites this file for every new version.
class Rbtop < Formula
  desc "Bashtop rewritten in Rust: fast terminal resource monitor"
  homepage "https://github.com/gbomacfly/rbtop"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/rbtop-v$version-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/rbtop-v$version-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_x86"
    end
  end

  on_linux do
    on_arm do
      url "$base/rbtop-v$version-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$lin_arm"
    end
    on_intel do
      url "$base/rbtop-v$version-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$lin_x86"
    end
  end

  def install
    bin.install "rbtop"
    # rbtop looks in <prefix>/share/rbtop/themes next to its bin/ directory
    pkgshare.install "themes"
    doc.install "README.md", "README.de.md", "CHANGELOG.md"
  end

  test do
    assert_match "rbtop #{version}", shell_output("#{bin}/rbtop --version")
    assert_path_exists pkgshare/"themes/nord.theme"
  end
end
EOF
